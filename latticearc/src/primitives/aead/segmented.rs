//! Fixed-geometry segmented AEAD: an object of known length is split into
//! 64 KiB records, each sealed under its own HKDF-SHA256-derived AES-256-GCM
//! key and authenticated against the whole object's dimensions.
//!
//! # Threat model
//!
//! The adversary controls every record byte the decryptor reads. The
//! object's dimensions ([`SegmentedContext`]) come from caller metadata that
//! is already authenticated by other means; they are never read from the
//! records. The guarantees are:
//!
//! - **Fixed size.** Every record is exactly [`RECORD_LEN`] bytes and an
//!   object is exactly [`SegmentedContext::ciphertext_len`] bytes, so the
//!   ciphertext reveals only the record count. The last record's plaintext is
//!   zero padded under the AEAD; the decryptor rejects nonzero padding.
//! - **Truncation, reordering, splicing and extension are detected.** Each
//!   record's key and associated data bind the object binding, object id,
//!   generation, plaintext length, record count, the record's index and a
//!   final-record flag. A record moved to another index or object, or a
//!   stream cut short or extended, fails; [`SegmentedDecryptor::finish`]
//!   succeeds only after exactly every record was accepted.
//! - **One failure retires the handle.** Any error drops (and zeroizes) the
//!   secret the encryptor or decryptor holds; it cannot be retried.
//! - **Errors are opaque on the decrypt path.** A wrong length, wrong index,
//!   tag failure or bad padding all surface as the same
//!   [`AeadError::DecryptionFailed`] string. After that first failure the
//!   retired decryptor answers every call with [`AeadError::StreamExhausted`];
//!   that reports the caller's own handle state after a failure it was
//!   already told about, so it carries no information about any record.
//!
//! Out of scope: confidentiality of the record count, and nonce-misuse
//! resistance. Each record nonce is 96 random bits under a key that is unique
//! per (secret, generation, record index), so a key never seals two records
//! unless the caller reuses a generation; draw a fresh generation (see
//! [`SegmentedContext::with_random_generation`]) for every object version.
//!
//! **Generation reuse breaks version separation.** Two object versions sealed
//! under the same secret, generation and dimensions (labels, binding, object
//! id and plaintext length) share every record key and associated data, so a
//! record of one version opens as the same-index record of the other: an
//! adversary can substitute records between the versions or roll the whole
//! object back. The all-zero generation is rejected as an unset value.
//!
//! The decryptor releases each record's plaintext as soon as it
//! authenticates; callers must not act on the object until
//! [`SegmentedDecryptor::finish`] succeeds and their input has ended.
//!
//! # Construction
//!
//! All labels are caller parameters; this module defines none.
//!
//! ```text
//! records     = max(1, ceil(plaintext_len / 65508))
//! canonical_L(i) = L || binding || object_id (32) || generation (32)
//!               || plaintext_len (u64 BE) || records (u64 BE) || i (u64 BE)
//!               || final (1: 0x01 iff i == records - 1, else 0x00)
//! key_i       = HKDF-SHA256(ikm = secret, salt = generation,
//!                           info = canonical_{record_key label}(i), L = 32)
//! aad_i       = canonical_{record_aad label}(i)
//! record_i    = nonce_i (12, random) || AES-256-GCM(key_i, nonce_i, aad_i,
//!                                          M_i || zeros to 65508 bytes) || tag (16)
//! ```
//!
//! The two labels must differ and neither may be a prefix of the other, so a
//! record-key `info` never equals a record's associated data whatever the
//! bindings; [`SegmentedContext::new`] rejects any other pair.
//! `binding` is caller-defined bytes (for example a format version, a purpose
//! code and a key identity) and is not length-prefixed: a caller must keep
//! each (label, binding) pair unambiguous, for instance by giving every label
//! a binding of one fixed length. [`derive_object_id`] computes
//! `SHA-256(prefix || locator)` for callers that name objects by a locator.
//!
//! The layout is pinned by `latticearc/tests/fixtures/segmented-v1.json`,
//! generated by an independent Python HKDF-SHA256/AES-256-GCM reference
//! implementation (`scripts/generate-segmented-fixtures.py`).

use crate::primitives::aead::aes_gcm::AesGcm256;
use crate::primitives::aead::{AeadCipher, AeadError, NONCE_LEN, Nonce, TAG_LEN, is_all_zero_key};
use crate::primitives::ct::is_all_zero_bytes;
use crate::primitives::hash::sha2::sha256;
use crate::primitives::kdf::hkdf::hkdf_with_context;
use crate::primitives::rand::try_fill_bytes;
use zeroize::Zeroizing;

/// Length of every ciphertext record: nonce (12) || ciphertext || tag (16).
pub const RECORD_LEN: usize = 65_536;

/// Plaintext bytes per record (`RECORD_LEN - 12 - 16`); the last record is
/// zero padded to this length before encryption.
pub const PAYLOAD_LEN: usize = 65_508;

/// Largest accepted object plaintext length (2 GiB).
pub const MAX_PLAINTEXT_LEN: u64 = 2 << 30;

/// Length of the secret input keying material.
pub const SECRET_LEN: usize = 32;

/// Length of the object id.
pub const OBJECT_ID_LEN: usize = 32;

/// Length of the generation (HKDF salt, unique per object version).
pub const GENERATION_LEN: usize = 32;

/// [`PAYLOAD_LEN`] as `u64` for length arithmetic.
const PAYLOAD_LEN_U64: u64 = 65_508;

/// [`RECORD_LEN`] as `u64` for length arithmetic.
const RECORD_LEN_U64: u64 = 65_536;

/// Bytes of a canonical encoding after the label and binding:
/// object id, generation, length, records, index, final flag.
const CANONICAL_SUFFIX_LEN: usize = OBJECT_ID_LEN + GENERATION_LEN + 8 + 8 + 8 + 1;

/// Single opaque string for every adversary-reachable decrypt failure.
const DECRYPTION_FAILED: &str = "decryption failed";

/// Single opaque string for every encrypt-side internal failure.
const ENCRYPTION_FAILED: &str = "encryption failed";

// ============================================================================
// Geometry
// ============================================================================

/// Record count for `plaintext_len`: `max(1, ceil(plaintext_len / PAYLOAD_LEN))`.
/// `None` above [`MAX_PLAINTEXT_LEN`].
fn record_count_for(plaintext_len: u64) -> Option<u64> {
    if plaintext_len > MAX_PLAINTEXT_LEN {
        return None;
    }
    Some(plaintext_len.div_ceil(PAYLOAD_LEN_U64).max(1))
}

/// Plaintext bytes carried by record `index`: [`PAYLOAD_LEN`] for every record
/// but the last, the remainder for the last. `None` when `index >= records`.
fn payload_len_at(plaintext_len: u64, records: u64, index: u64) -> Option<usize> {
    if index >= records {
        return None;
    }
    let start = index.checked_mul(PAYLOAD_LEN_U64)?;
    let remaining = plaintext_len.checked_sub(start)?;
    usize::try_from(remaining.min(PAYLOAD_LEN_U64)).ok()
}

