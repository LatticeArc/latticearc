/// Caller-defined domain labels; both must be non-empty.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct SegmentedLabels<'a> {
    /// Prefix of the HKDF `info` that derives each record key.
    pub record_key: &'a [u8],
    /// Prefix of each record's AES-GCM associated data.
    pub record_aad: &'a [u8],
}

/// Dimensions and identity of one object, from caller metadata that is
/// already authenticated. It contains no key material.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SegmentedContext {
    record_key_label: Vec<u8>,
    record_aad_label: Vec<u8>,
    binding: Vec<u8>,
    object_id: [u8; OBJECT_ID_LEN],
    generation: [u8; GENERATION_LEN],
    plaintext_len: u64,
    records: u64,
}

impl SegmentedContext {
    /// Builds the context of an object of `plaintext_len` bytes.
    ///
    /// `generation` must be fresh for every object version. Reusing one under
    /// the same secret and dimensions lets an adversary substitute records
    /// between the versions or roll the object back (see the module docs);
    /// prefer [`with_random_generation`](Self::with_random_generation).
    ///
    /// # Errors
    /// - [`AeadError::EmptyContext`] if either label is empty.
    /// - [`AeadError::AmbiguousLabels`] if the labels are equal or one is a
    ///   prefix of the other.
    /// - [`AeadError::WeakGeneration`] if `generation` is all zero.
    /// - [`AeadError::InvalidSegmentLength`] if `plaintext_len` exceeds
    ///   [`MAX_PLAINTEXT_LEN`].
    pub fn new(
        labels: SegmentedLabels<'_>,
        binding: &[u8],
        object_id: [u8; OBJECT_ID_LEN],
        generation: [u8; GENERATION_LEN],
        plaintext_len: u64,
    ) -> Result<Self, AeadError> {
        if labels.record_key.is_empty() || labels.record_aad.is_empty() {
            return Err(AeadError::EmptyContext);
        }
        // Equal labels count as prefixes of each other.
        if labels.record_key.starts_with(labels.record_aad)
            || labels.record_aad.starts_with(labels.record_key)
        {
            return Err(AeadError::AmbiguousLabels);
        }
        if is_all_zero_bytes(&generation) {
            return Err(AeadError::WeakGeneration);
        }
        let records = record_count_for(plaintext_len).ok_or(AeadError::InvalidSegmentLength)?;
        Ok(Self {
            record_key_label: labels.record_key.to_vec(),
            record_aad_label: labels.record_aad.to_vec(),
            binding: binding.to_vec(),
            object_id,
            generation,
            plaintext_len,
            records,
        })
    }

    /// Like [`new`](Self::new) with a generation drawn from the OS CSPRNG,
    /// for a new object version.
    ///
    /// # Errors
    /// As [`new`](Self::new), and [`AeadError::EncryptionFailed`] if the OS
    /// entropy source fails.
    pub fn with_random_generation(
        labels: SegmentedLabels<'_>,
        binding: &[u8],
        object_id: [u8; OBJECT_ID_LEN],
        plaintext_len: u64,
    ) -> Result<Self, AeadError> {
        let mut generation = [0u8; GENERATION_LEN];
        try_fill_bytes(&mut generation)
            .map_err(|_e| AeadError::EncryptionFailed(ENCRYPTION_FAILED.to_string()))?;
        Self::new(labels, binding, object_id, generation, plaintext_len)
    }

    /// Authenticated object plaintext length.
    #[must_use]
    pub const fn plaintext_len(&self) -> u64 {
        self.plaintext_len
    }

    /// Number of records; an empty object still has one.
    #[must_use]
    pub const fn record_count(&self) -> u64 {
        self.records
    }

    /// Exact ciphertext length: `record_count() * RECORD_LEN`.
    #[must_use]
    pub const fn ciphertext_len(&self) -> u64 {
        // records <= ceil(2^31 / 65508) + 1, so the product cannot overflow.
        self.records.saturating_mul(RECORD_LEN_U64)
    }

    /// Object id bound into every record.
    #[must_use]
    pub const fn object_id(&self) -> [u8; OBJECT_ID_LEN] {
        self.object_id
    }

    /// Generation (HKDF salt) bound into every record.
    #[must_use]
    pub const fn generation(&self) -> [u8; GENERATION_LEN] {
        self.generation
    }

    /// Plaintext bytes carried by record `index`.
    ///
    /// # Errors
    /// [`AeadError::InvalidSegmentLength`] if `index >= record_count()`.
    pub fn payload_len(&self, index: u64) -> Result<usize, AeadError> {
        payload_len_at(self.plaintext_len, self.records, index)
            .ok_or(AeadError::InvalidSegmentLength)
    }

    /// `label || binding || object_id || generation || length || records ||
    /// index || final`. `None` when `index >= records`.
    fn canonical(&self, label: &[u8], index: u64) -> Option<Vec<u8>> {
        payload_len_at(self.plaintext_len, self.records, index)?;
        let final_flag = u8::from(index == self.records.saturating_sub(1));
        let mut bytes = Vec::with_capacity(
            label.len().saturating_add(self.binding.len()).saturating_add(CANONICAL_SUFFIX_LEN),
        );
        bytes.extend_from_slice(label);
        bytes.extend_from_slice(&self.binding);
        bytes.extend_from_slice(&self.object_id);
        bytes.extend_from_slice(&self.generation);
        bytes.extend_from_slice(&self.plaintext_len.to_be_bytes());
        bytes.extend_from_slice(&self.records.to_be_bytes());
        bytes.extend_from_slice(&index.to_be_bytes());
        bytes.push(final_flag);
        Some(bytes)
    }

    /// Associated data of record `index` (public; contains no key material).
    ///
    /// # Errors
    /// [`AeadError::InvalidSegmentLength`] if `index >= record_count()`.
    pub fn record_aad(&self, index: u64) -> Result<Vec<u8>, AeadError> {
        self.canonical(&self.record_aad_label, index).ok_or(AeadError::InvalidSegmentLength)
    }

    /// `HKDF-SHA256(secret, generation, canonical_{record_key}(index))`.
    fn derive_record_key(
        &self,
        secret: &[u8; SECRET_LEN],
        index: u64,
    ) -> Option<Zeroizing<[u8; 32]>> {
        let info = self.canonical(&self.record_key_label, index)?;
        let okm = hkdf_with_context(secret, Some(&self.generation), &info, 32).ok()?;
        // Copy straight into the zeroizing buffer so no plain stack copy of
        // the key outlives this call.
        let mut key = Zeroizing::new([0u8; 32]);
        let derived = okm.expose_secret();
        if derived.len() != key.len() {
            return None;
        }
        key.copy_from_slice(derived);
        Some(key)
    }

    /// Record key for `index`, exposed only for known-answer tests.
    ///
    /// # Errors
    /// [`AeadError::InvalidSegmentLength`] if `index >= record_count()` or
    /// key derivation fails.
    #[cfg(any(test, feature = "kat-test-vectors"))]
    pub fn record_key(
        &self,
        secret: &[u8; SECRET_LEN],
        index: u64,
    ) -> Result<Zeroizing<[u8; 32]>, AeadError> {
        self.derive_record_key(secret, index).ok_or(AeadError::InvalidSegmentLength)
    }

    fn record_cipher(&self, secret: &[u8; SECRET_LEN], index: u64) -> Option<AesGcm256> {
        let key = self.derive_record_key(secret, index)?;
        AesGcm256::new(key.as_slice()).ok()
    }
}

