/// Seals `chunk` as record `index`. `chunk` must be exactly the record's
/// payload length.
fn seal_record(
    context: &SegmentedContext,
    secret: &[u8; SECRET_LEN],
    index: u64,
    chunk: &[u8],
    nonce: &Nonce,
) -> Result<Vec<u8>, AeadError> {
    let opaque = || AeadError::EncryptionFailed(ENCRYPTION_FAILED.to_string());
    if chunk.len() != context.payload_len(index)? {
        return Err(AeadError::InvalidSegmentLength);
    }
    let mut padded = Zeroizing::new(vec![0u8; PAYLOAD_LEN]);
    padded.get_mut(..chunk.len()).ok_or_else(opaque)?.copy_from_slice(chunk);
    let cipher = context.record_cipher(secret, index).ok_or_else(opaque)?;
    let aad = context.record_aad(index)?;
    let (ciphertext, tag) = cipher.encrypt(nonce, &padded, Some(&aad))?;
    let mut record = Vec::with_capacity(RECORD_LEN);
    record.extend_from_slice(nonce);
    record.extend_from_slice(&ciphertext);
    record.extend_from_slice(&tag);
    if record.len() != RECORD_LEN {
        return Err(opaque());
    }
    Ok(record)
}

/// Opens record `index`, checks its padding is all zero and returns the
/// payload.
fn open_record(
    context: &SegmentedContext,
    secret: &[u8; SECRET_LEN],
    index: u64,
    record: &[u8],
) -> Result<Zeroizing<Vec<u8>>, AeadError> {
    let opaque = || AeadError::DecryptionFailed(DECRYPTION_FAILED.to_string());
    if record.len() != RECORD_LEN {
        return Err(opaque());
    }
    let payload = context.payload_len(index).map_err(|_e| opaque())?;
    let (nonce, rest) = record.split_first_chunk::<NONCE_LEN>().ok_or_else(opaque)?;
    let (ciphertext, tag) = rest.split_last_chunk::<TAG_LEN>().ok_or_else(opaque)?;
    let cipher = context.record_cipher(secret, index).ok_or_else(opaque)?;
    let aad = context.record_aad(index).map_err(|_e| opaque())?;
    let mut plaintext =
        cipher.decrypt(nonce, ciphertext, tag, Some(&aad)).map_err(|_e| opaque())?;
    if plaintext.len() != PAYLOAD_LEN {
        return Err(opaque());
    }
    let padding = plaintext.get(payload..).ok_or_else(opaque)?;
    if !padding.is_empty() && !is_all_zero_bytes(padding) {
        return Err(opaque());
    }
    // The removed bytes were verified zero; the payload keeps the original
    // bounded allocation and is zeroized on drop.
    plaintext.truncate(payload);
    Ok(plaintext)
}

fn checked_secret(secret: &[u8; SECRET_LEN]) -> Result<Zeroizing<[u8; SECRET_LEN]>, AeadError> {
    if is_all_zero_key(secret) {
        return Err(AeadError::WeakKey);
    }
    Ok(Zeroizing::new(*secret))
}

