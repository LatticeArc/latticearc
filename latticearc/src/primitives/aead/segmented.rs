/// Sequential one-use encryptor: call [`seal_next`](Self::seal_next) once per
/// record in order, then [`finish`](Self::finish). Any error retires it and
/// zeroizes the secret it holds.
pub struct SegmentedEncryptor {
    context: SegmentedContext,
    secret: Option<Zeroizing<[u8; SECRET_LEN]>>,
    next_index: u64,
}

impl std::fmt::Debug for SegmentedEncryptor {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("SegmentedEncryptor")
            .field("secret", &"[REDACTED]")
            .field("next_index", &self.next_index)
            .field("retired", &self.secret.is_none())
            .finish_non_exhaustive()
    }
}

impl SegmentedEncryptor {
    /// Starts encrypting the object described by `context` under `secret`.
    ///
    /// # Errors
    /// [`AeadError::WeakKey`] if `secret` is all zero.
    pub fn new(secret: &[u8; SECRET_LEN], context: SegmentedContext) -> Result<Self, AeadError> {
        Ok(Self { context, secret: Some(checked_secret(secret)?), next_index: 0 })
    }

    /// The object's context, to store with (or derive from) authenticated
    /// metadata.
    #[must_use]
    pub const fn context(&self) -> &SegmentedContext {
        &self.context
    }

    /// Index the next sealed record will receive.
    #[must_use]
    pub const fn next_index(&self) -> u64 {
        self.next_index
    }

    /// Seals the next record under a fresh random nonce. `chunk` must be
    /// exactly [`SegmentedContext::payload_len`] bytes for this index; the
    /// returned record is [`RECORD_LEN`] bytes.
    ///
    /// # Errors
    /// - [`AeadError::StreamExhausted`] if the handle is retired or every
    ///   record was already sealed.
    /// - [`AeadError::InvalidSegmentLength`] if `chunk` has the wrong length.
    /// - [`AeadError::EncryptionFailed`] if the entropy source, key
    ///   derivation or AES-GCM fails.
    #[must_use = "the sealed record must be stored"]
    pub fn seal_next(&mut self, chunk: &[u8]) -> Result<Vec<u8>, AeadError> {
        let mut nonce = [0u8; NONCE_LEN];
        if try_fill_bytes(&mut nonce).is_err() {
            self.secret = None;
            return Err(AeadError::EncryptionFailed(ENCRYPTION_FAILED.to_string()));
        }
        self.seal_with(chunk, &nonce)
    }

    /// [`seal_next`](Self::seal_next) under a caller-chosen nonce, exposed
    /// only for known-answer tests. Reusing a nonce under the same secret,
    /// generation and index breaks AES-GCM.
    ///
    /// # Errors
    /// As [`seal_next`](Self::seal_next).
    #[cfg(any(test, feature = "kat-test-vectors"))]
    #[must_use = "the sealed record must be stored"]
    pub fn seal_next_with_nonce(
        &mut self,
        chunk: &[u8],
        nonce: &Nonce,
    ) -> Result<Vec<u8>, AeadError> {
        self.seal_with(chunk, nonce)
    }

    fn seal_with(&mut self, chunk: &[u8], nonce: &Nonce) -> Result<Vec<u8>, AeadError> {
        let result = self.try_seal(chunk, nonce);
        if result.is_err() {
            self.secret = None;
        }
        result
    }

    fn try_seal(&mut self, chunk: &[u8], nonce: &Nonce) -> Result<Vec<u8>, AeadError> {
        let index = self.next_index;
        if index >= self.context.records {
            return Err(AeadError::StreamExhausted);
        }
        let secret = self.secret.as_ref().ok_or(AeadError::StreamExhausted)?;
        let record = seal_record(&self.context, secret, index, chunk, nonce)?;
        self.next_index = index.checked_add(1).ok_or(AeadError::SegmentCounterExhausted)?;
        Ok(record)
    }

    /// Completes the object and zeroizes the secret.
    ///
    /// # Errors
    /// [`AeadError::EncryptionFailed`] if the handle was retired or not every
    /// record was sealed.
    pub fn finish(mut self) -> Result<(), AeadError> {
        let active = self.secret.take().is_some();
        if active && self.next_index == self.context.records {
            Ok(())
        } else {
            Err(AeadError::EncryptionFailed(ENCRYPTION_FAILED.to_string()))
        }
    }
}

