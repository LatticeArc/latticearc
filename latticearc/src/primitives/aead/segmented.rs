// Object id
// ============================================================================

/// Object id `SHA-256(prefix || locator)` for a caller-defined, non-empty
/// domain `prefix`.
///
/// # Errors
/// - [`AeadError::EmptyContext`] if `prefix` is empty.
/// - [`AeadError::EncryptionFailed`] if the input exceeds the hash input limit.
pub fn derive_object_id(prefix: &[u8], locator: &[u8]) -> Result<[u8; OBJECT_ID_LEN], AeadError> {
    if prefix.is_empty() {
        return Err(AeadError::EmptyContext);
    }
    let mut input = Vec::with_capacity(prefix.len().saturating_add(locator.len()));
    input.extend_from_slice(prefix);
    input.extend_from_slice(locator);
    sha256(&input).map_err(|_e| AeadError::EncryptionFailed(ENCRYPTION_FAILED.to_string()))
}

