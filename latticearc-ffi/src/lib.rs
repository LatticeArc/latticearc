/// Process-wide report on memory locking of secret buffers.
///
/// On Android the per-process `RLIMIT_MEMLOCK` is often 64 KiB, so
/// `failed_buffers > 0` is expected there once enough secrets are alive;
/// show it rather than hide it.
#[derive(Debug, Clone, PartialEq, Eq, uniffi::Record)]
pub struct MemoryLockStatus {
    /// `true` when this build attempts to lock secret buffers.
    pub supported: bool,
    /// `true` when the library was built with the `secret-mlock` feature.
    pub feature_enabled: bool,
    /// Live secret buffers whose pages are locked.
    pub locked_buffers: u64,
    /// Lock attempts that failed since process start.
    pub failed_buffers: u64,
    /// OS error text of the most recent failed attempt, if any.
    pub last_error: Option<String>,
}

/// Returns the process-wide [`MemoryLockStatus`].
#[uniffi::export]
#[must_use]
pub fn memory_lock_status() -> MemoryLockStatus {
    let s = latticearc::memory_lock_status();
    MemoryLockStatus {
        supported: s.supported,
        feature_enabled: s.feature_enabled,
        locked_buffers: u64::try_from(s.locked_buffers).unwrap_or(u64::MAX),
        failed_buffers: u64::try_from(s.failed_buffers).unwrap_or(u64::MAX),
        last_error: s.last_error,
    }
}

/// The LatticeArc version compiled into this library.
#[uniffi::export]
#[must_use]
pub fn version() -> String {
    env!("CARGO_PKG_VERSION").to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn version_is_the_workspace_version() {
        assert_eq!(version(), env!("CARGO_PKG_VERSION"));
    }

    #[test]
    fn memory_lock_status_reports_feature() {
        let s = memory_lock_status();
        assert_eq!(s.feature_enabled, cfg!(feature = "secret-mlock"));
        if !s.feature_enabled {
            assert!(!s.supported);
            assert_eq!(s.locked_buffers, 0);
        }
    }

    #[cfg(all(feature = "secret-mlock", not(target_os = "windows")))]
    #[test]
    fn locked_buffer_count_tracks_live_secrets() {
        let before = memory_lock_status().locked_buffers;
        let s = SecretBytes::import(vec![1u8; 64]);
        let during = memory_lock_status();
        assert!(during.supported);
        if s.is_locked() {
            assert!(during.locked_buffers > before);
        }
        drop(s);
    }
}
