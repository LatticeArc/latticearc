//! UniFFI bindings for LatticeArc.
//!
//! This crate exposes the LatticeArc 0.13 mobile-core APIs to Swift and
//! Kotlin through [UniFFI](https://mozilla.github.io/uniffi-rs/): Argon2id,
//! HKDF and SP 800-108 with required contexts, committing key wrap,
//! streaming AEAD, hybrid ML-KEM + X25519 encapsulation and encryption,
//! hybrid ML-DSA + Ed25519 and plain ML-DSA signatures (context-bound,
//! pre-hashed and seed-derived), the binary wire format, and the memory-lock
//! status. See `docs/FFI.md` for the language-level API map and the build
//! scripts under `scripts/ffi/`.
//!
//! # Rules the surface follows
//!
//! - **Secrets are handles.** Derived keys, unwrapped keys, shared secrets
//!   and signing keys are opaque objects ([`SecretBytes`],
//!   [`HybridKemSecretKey`], [`HybridSigningKey`], [`MlDsaSigningKey`]).
//!   Secret bytes cross the boundary only through methods named `export*`.
//! - **Errors are typed.** Every failure is a [`LatticeArcError`] variant;
//!   nothing panics across the boundary. Verification mismatches return
//!   `false`; forged ciphertexts and wrong keys in the AEAD, key-wrap,
//!   stream and hybrid-encryption paths return the opaque
//!   `AuthenticationFailed`. ML-KEM decapsulation uses implicit rejection
//!   and never fails for a wrong key; the authenticated step that follows
//!   does.
//! - **Contexts are mandatory** wherever the Rust API requires them: hybrid
//!   KEM and signatures, HKDF, SP 800-108, key wrap, stream `aad` and
//!   HashML-DSA. Plain ML-DSA `sign` / `verify` accept an empty context, as
//!   FIPS 204 does.
//! - **Public values use the wire format** (`docs/WIRE_FORMAT.md`), so a
//!   key or ciphertext written on one platform parses on every other.
//!
//! The hand-written source of this crate contains no `unsafe`; the C ABI is
//! generated by UniFFI's macros.

