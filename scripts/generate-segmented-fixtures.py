#!/usr/bin/env python3
"""Regenerate the segmented AEAD v1 known-answer vectors without calling LatticeArc.

Usage: python3 scripts/generate-segmented-fixtures.py
Writes latticearc/tests/fixtures/segmented-v1.json. This is an independent
HKDF-SHA256 / AES-256-GCM implementation of the layout documented in
latticearc/src/primitives/aead/segmented.rs (it needs the `cryptography`
package); latticearc/tests/segmented_aead_kat.rs checks that the Rust code
reproduces every record byte for byte. Labels, keys and inputs are synthetic.
"""
import hashlib
import json
import struct
from pathlib import Path

from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.hkdf import HKDF

RECORD_LEN = 65536
PAYLOAD_LEN = 65508
RECORD_KEY_LABEL = b"example/segmented/record-key/"
RECORD_AAD_LABEL = b"example/segmented/record-aad/"
OBJECT_ID_PREFIX = b"example/segmented/object-id/"


def filler(length, seed):
    out, b = bytearray(), seed
    for _ in range(length):
        b = (b * 29 + 7) & 0xFF
        out.append(b)
    return bytes(out)


SECRET = filler(32, 1)
GENERATION = filler(32, 2)
NONCE = filler(12, 3)
LOCATOR = filler(40, 4)
OBJECT_ID = hashlib.sha256(OBJECT_ID_PREFIX + LOCATOR).digest()
BINDINGS = {"filler67": filler(67, 5), "empty": b""}


def records_for(length):
    return max(1, -(-length // PAYLOAD_LEN))


def canonical(label, binding, length, index, final=None):
    records = records_for(length)
    if final is None:
        final = index == records - 1
    return (label + binding + OBJECT_ID + GENERATION
            + struct.pack(">QQQ", length, records, index) + bytes([int(final)]))


def record_key(binding, length, index):
    info = canonical(RECORD_KEY_LABEL, binding, length, index)
    return HKDF(algorithm=hashes.SHA256(), length=32, salt=GENERATION, info=info).derive(SECRET)


def seal(binding, length, index, padded, final=None):
    assert len(padded) == PAYLOAD_LEN
    aad = canonical(RECORD_AAD_LABEL, binding, length, index, final)
    record = NONCE + AESGCM(record_key(binding, length, index)).encrypt(NONCE, padded, aad)
    assert len(record) == RECORD_LEN
    return record


def plaintext(length):
    return bytes(i % 251 for i in range(length))


def padded_chunk(data, index):
    chunk = data[index * PAYLOAD_LEN:(index + 1) * PAYLOAD_LEN]
    return chunk + bytes(PAYLOAD_LEN - len(chunk))


def case(binding_name, length):
    binding, data = BINDINGS[binding_name], plaintext(length)
    records = [seal(binding, length, i, padded_chunk(data, i)) for i in range(records_for(length))]
    return {"binding": binding_name, "length": length, "records": len(records),
            "record_sha256": [hashlib.sha256(r).hexdigest() for r in records],
            "stream_sha256": hashlib.sha256(b"".join(records)).hexdigest()}


LENGTHS = [0, 1, PAYLOAD_LEN - 1, PAYLOAD_LEN, PAYLOAD_LEN + 1, RECORD_LEN,
           2 * PAYLOAD_LEN, 2 * PAYLOAD_LEN + 1]
cases = [case("filler67", n) for n in LENGTHS] + [case("empty", n) for n in (0, 1)]

binding = BINDINGS["filler67"]
detail = {"binding": "filler67", "length": 1, "index": 0,
          "record_key_hex": record_key(binding, 1, 0).hex(),
          "aad_hex": canonical(RECORD_AAD_LABEL, binding, 1, 0).hex()}

# Records an honest encryptor never produces, each authenticated under the
# genuine record key: the decryptor must still reject them.
nonzero_padding = bytearray(padded_chunk(plaintext(1), 0))
nonzero_padding[1] = 1
negatives = [
    {"name": "nonzero_padding", "binding": "filler67", "length": 1, "index": 0,
     "record_sha256": hashlib.sha256(seal(binding, 1, 0, bytes(nonzero_padding))).hexdigest()},
    {"name": "final_flag_cleared", "binding": "filler67", "length": 1, "index": 0,
     "record_sha256": hashlib.sha256(
         seal(binding, 1, 0, padded_chunk(plaintext(1), 0), final=False)).hexdigest()},
]

fixtures = {
    "format": "LatticeArc segmented AEAD v1 (primitives::aead::segmented)",
    "provenance": "generated by an independent Python HKDF-SHA256/AES-256-GCM reference "
                  "implementation (scripts/generate-segmented-fixtures.py)",
    "filler": "b = seed; repeat len times: b = (b * 29 + 7) mod 256, emit b",
    "plaintext": "byte i of an object is i mod 251",
    "record_len": RECORD_LEN,
    "payload_len": PAYLOAD_LEN,
    "record_key_label_hex": RECORD_KEY_LABEL.hex(),
    "record_aad_label_hex": RECORD_AAD_LABEL.hex(),
    "object_id_prefix_hex": OBJECT_ID_PREFIX.hex(),
    "secret_hex": SECRET.hex(),
    "generation_hex": GENERATION.hex(),
    "nonce_hex": NONCE.hex(),
    "locator_hex": LOCATOR.hex(),
    "object_id_hex": OBJECT_ID.hex(),
    "bindings": {name: value.hex() for name, value in BINDINGS.items()},
    "cases": cases,
    "detail": detail,
    "negatives": negatives,
}

out = Path(__file__).resolve().parents[1] / "latticearc/tests/fixtures/segmented-v1.json"
out.write_text(json.dumps(fixtures, indent=1) + "\n")
print(f"wrote {out}")
